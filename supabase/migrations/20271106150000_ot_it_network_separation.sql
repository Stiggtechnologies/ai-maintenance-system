create or replace function public.begin_connector_run(
  p_connector_key text,
  p_entity_type text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $nz$
declare
  v_org uuid := app_current_org();
  c connectors%rowtype;
  v_run uuid;
  v_from timestamptz;
  v_crossing jsonb;
  v_has_zone boolean;
begin
  select * into c from connectors
  where organization_id = v_org and connector_key = p_connector_key;
  if not found then
    return jsonb_build_object('error', 'connector not registered');
  end if;
  if not c.enabled then
    return jsonb_build_object('error',
      format('connector "%s" is registered but not enabled', p_connector_key));
  end if;

  v_crossing := public.connector_zone_crossing(v_org, p_connector_key, 'read');
  select exists (
    select 1 from public.network_zones z
    where z.organization_id = v_org
      and z.zone_status = 'adopted'
      and z.superseded_by_zone_id is null
  ) into v_has_zone;
  if v_has_zone and coalesce((v_crossing->>'allowed')::boolean, false) is not true then
    return jsonb_build_object(
      'error', coalesce(v_crossing->>'reason', 'no_adopted_zone_assignment'),
      'zone_separation', 'refused',
      'note', 'This tenant has an adopted network zone. Connector reads require an adopted zone assignment.'
    );
  end if;

  select last_position into v_from from ingest_watermarks
  where connector_id = c.id and entity_type = p_entity_type;

  insert into connector_runs (
    organization_id, connector_id, entity_type,
    run_type, status, started_at, watermark_from, triggered_by
  ) values (
    v_org, c.id, p_entity_type, 'sync', 'running', now(), v_from, auth.uid()
  ) returning id into v_run;

  return jsonb_build_object(
    'run_id', v_run,
    'watermark_from', v_from,
    'zone_separation', case when v_has_zone then 'assigned' else 'unzoned' end,
    'note', case
      when not v_has_zone then
        'No adopted network zone. This run is unzoned, which is not OT/IT separation.'
      when v_from is null then 'No prior watermark: this is a full load.'
      else 'Incremental from the last successful position.'
    end
  );
end;
