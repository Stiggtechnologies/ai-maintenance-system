create or replace function public.propose_network_zone(
  p_zone_key text,
  p_label text,
  p_purdue_level integer,
  p_egress_permitted boolean,
  p_egress_route text,
  p_basis text,
  p_supersedes_zone_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $nz$
declare
  v_org uuid := public.app_current_org();
  v_uid uuid := auth.uid();
  v_role text;
  v_key text := lower(btrim(coalesce(p_zone_key, '')));
  v_label text := btrim(coalesce(p_label, ''));
  v_route text := nullif(btrim(coalesce(p_egress_route, '')), '');
  v_basis text := btrim(coalesce(p_basis, ''));
  v_version integer;
  v_id bigint;
  v_current public.network_zones%rowtype;
begin
  select role into v_role from public.user_profiles
  where id = v_uid and organization_id = v_org;
  if v_org is null or v_uid is null or coalesce(v_role, '') = 'ai_admin' then
    return jsonb_build_object('error', 'The AI-operator identity cannot propose a network zone');
  end if;
  if coalesce(v_role, '') not in ('admin', 'executive') then
    return jsonb_build_object('error', 'An assured named administrator or executive is required');
  end if;
  if v_key !~ '^[a-z0-9][a-z0-9_-]{1,62}$' then
    return jsonb_build_object('error', 'Zone key must be 2-63 lowercase letters, digits, hyphens or underscores');
  end if;
  if length(v_label) < 3 or length(v_label) > 160 then
    return jsonb_build_object('error', 'Zone label must be 3-160 characters');
  end if;
  if p_purdue_level is null or p_purdue_level < 0 or p_purdue_level > 5 then
    return jsonb_build_object('error', 'Declare a Purdue level from 0 to 5');
  end if;
  if coalesce(p_egress_permitted, false) and v_route is null then
    return jsonb_build_object('error', 'Permitted egress requires a route');
  end if;
  if not coalesce(p_egress_permitted, false) then
    v_route := null;
  end if;
  if length(v_basis) < 30 then
    return jsonb_build_object('error', 'State the zone boundary, what may cross it, and the residual risk in at least 30 characters');
  end if;
  if exists (
    select 1 from public.network_zones z
    where z.organization_id = v_org
      and z.zone_key = v_key
      and z.zone_status = 'proposed'
  ) then
    return jsonb_build_object('error', 'Decide the current proposal for this zone key first');
  end if;

  select * into v_current from public.network_zones z
  where z.organization_id = v_org
    and z.zone_key = v_key
    and z.zone_status = 'adopted'
    and z.superseded_by_zone_id is null
  for update;
  if found and (p_supersedes_zone_id is null or p_supersedes_zone_id <> v_current.id) then
    return jsonb_build_object('error', 'A revision must explicitly supersede the exact current zone');
  end if;
  if not found and p_supersedes_zone_id is not null then
    return jsonb_build_object('error', 'No current zone exists to supersede for this key');
  end if;

  select coalesce(max(version), 0) + 1 into v_version
  from public.network_zones z
  where z.organization_id = v_org and z.zone_key = v_key;

  perform set_config('app.network_zone_writer', 'governed', true);
  insert into public.network_zones(
    organization_id, zone_key, label, purdue_level, egress_permitted, egress_route,
    version, zone_status, basis, proposed_by, proposed_at, supersedes_zone_id
  ) values (
    v_org, v_key, v_label, p_purdue_level, coalesce(p_egress_permitted, false), v_route,
    v_version, 'proposed', v_basis, v_uid, now(), p_supersedes_zone_id
  ) returning id into v_id;
  perform set_config('app.network_zone_writer', '', true);

  insert into public.audit_events(organization_id, entity_type, actor, event_data)
  values (
    v_org, 'network_zone', v_role,
    jsonb_build_object(
      'event', 'network_zone_proposed',
      'zone_id', v_id,
      'version', v_version,
      'zone_key', v_key,
      'purdue_level', p_purdue_level,
      'egress_permitted', coalesce(p_egress_permitted, false),
      'proposed_by', v_uid,
      'operational_authority', false
    )
  );
  insert into public.security_events(
    organization_id, actor_id, actor_label, event_type, severity, detail
  ) values (
    v_org, v_uid,
    (select coalesce(full_name, email) from public.user_profiles where id = v_uid),
    'admin_action', 'notice',
    'Proposed network zone ' || v_key || ' version ' || v_version
  );

  return jsonb_build_object(
    'zoneId', v_id,
    'version', v_version,
    'status', 'proposed',
    'independentReviewRequired', true,
    'operationalAuthority', false
  );
exception when others then
  perform set_config('app.network_zone_writer', '', true);
  raise;
end;
$nz$;

create or replace function public.decide_network_zone(
  p_zone_id bigint,
  p_decision text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $nz$
declare
  v_org uuid := public.app_current_org();
  v_uid uuid := auth.uid();
  v_role text;
  v_zone public.network_zones%rowtype;
  v_current public.network_zones%rowtype;
  v_status text;
begin
  select role into v_role from public.user_profiles
  where id = v_uid and organization_id = v_org;
  if v_org is null or v_uid is null or coalesce(v_role, '') = 'ai_admin' then
    return jsonb_build_object('error', 'The AI-operator identity cannot decide a network zone');
  end if;
  if coalesce(v_role, '') not in ('admin', 'executive') then
    return jsonb_build_object('error', 'An assured named administrator or executive is required');
  end if;
  if p_decision not in ('adopt', 'reject') then
    return jsonb_build_object('error', 'Decision must be adopt or reject');
  end if;
  if length(btrim(coalesce(p_reason, ''))) < 30 then
    return jsonb_build_object('error', 'State an independent decision and residual-risk basis of at least 30 characters');
  end if;
  if not public.app_actor_has_verified_mfa(v_uid) or public.app_current_aal() <> 'aal2' then
    return jsonb_build_object('error', 'Network zone disposition requires a verified factor and an AAL2 session');
  end if;

  select * into v_zone from public.network_zones
  where id = p_zone_id and organization_id = v_org and zone_status = 'proposed'
  for update;
  if not found then
    return jsonb_build_object('error', 'Proposed network zone not found in this tenant');
  end if;
  if v_zone.proposed_by = v_uid then
    return jsonb_build_object('error', 'The proposer cannot independently adopt or reject the same network zone');
  end if;
  if p_decision = 'adopt' and v_zone.purdue_level is null then
    return jsonb_build_object('error', 'Declare a Purdue level before adopting the zone');
  end if;
  if p_decision = 'adopt' then
    select * into v_current from public.network_zones z
    where z.organization_id = v_org
      and z.zone_key = v_zone.zone_key
      and z.zone_status = 'adopted'
      and z.superseded_by_zone_id is null
    for update;
    if found and v_zone.supersedes_zone_id is distinct from v_current.id then
      return jsonb_build_object('error', 'The proposal no longer supersedes the exact current zone; submit a new revision');
    end if;
    if not found and v_zone.supersedes_zone_id is not null then
      return jsonb_build_object('error', 'The zone selected for supersession is no longer current');
    end if;
  end if;

  v_status := case when p_decision = 'adopt' then 'adopted' else 'rejected' end;
  perform set_config('app.network_zone_writer', 'governed', true);
  if p_decision = 'adopt' and v_current.id is not null then
    update public.network_zones
    set zone_status = 'superseded', superseded_by_zone_id = v_zone.id
    where id = v_current.id and organization_id = v_org;
  end if;
  update public.network_zones
  set zone_status = v_status,
      decided_by = v_uid,
      decided_at = now(),
      decision_reason = btrim(p_reason)
  where id = v_zone.id and organization_id = v_org;
  perform set_config('app.network_zone_writer', '', true);

  insert into public.audit_events(organization_id, entity_type, actor, event_data)
  values (
    v_org, 'network_zone', v_role,
    jsonb_build_object(
      'event', 'network_zone_' || v_status,
      'zone_id', v_zone.id,
      'version', v_zone.version,
      'zone_key', v_zone.zone_key,
      'decision', p_decision,
      'proposed_by', v_zone.proposed_by,
      'decided_by', v_uid,
      'segregation_of_duties', true,
      'aal', 'aal2',
      'verified_factor', true,
      'operational_authority', false
    )
  );
  insert into public.security_events(
    organization_id, actor_id, actor_label, event_type, severity, detail
  ) values (
    v_org, v_uid,
    (select coalesce(full_name, email) from public.user_profiles where id = v_uid),
