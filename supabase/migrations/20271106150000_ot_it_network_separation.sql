create or replace function public.decide_connector_zone_assignment(
  p_assignment_id bigint,
  p_decision text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $nz$
declare
  v_org uuid := public.app_current_org();
  v_uid uuid := auth.uid();
  v_role text;
  v_row public.connector_zone_assignments%rowtype;
  v_current public.connector_zone_assignments%rowtype;
  v_zone public.network_zones%rowtype;
  v_status text;
begin
  select role into v_role from public.user_profiles
  where id = v_uid and organization_id = v_org;
  if v_org is null or v_uid is null or coalesce(v_role, '') = 'ai_admin' then
    return jsonb_build_object('error', 'The AI-operator identity cannot decide a connector zone assignment');
  end if;
  if coalesce(v_role, '') not in ('admin', 'executive') then
    return jsonb_build_object('error', 'An assured named administrator or executive is required');
  end if;
  if p_decision not in ('adopt', 'reject') then
    return jsonb_build_object('error', 'Decision must be adopt or reject');
  end if;
  if length(btrim(coalesce(p_reason, ''))) < 30 then
    return jsonb_build_object('error', 'State an independent decision and residual-risk basis of at least 30 characters');
  end if;
  if not public.app_actor_has_verified_mfa(v_uid) or public.app_current_aal() <> 'aal2' then
    return jsonb_build_object('error', 'Connector zone disposition requires a verified factor and an AAL2 session');
  end if;

  select * into v_row from public.connector_zone_assignments
  where id = p_assignment_id and organization_id = v_org and assignment_status = 'proposed'
  for update;
  if not found then
    return jsonb_build_object('error', 'Proposed connector zone assignment not found in this tenant');
  end if;
  if v_row.proposed_by = v_uid then
    return jsonb_build_object('error', 'The proposer cannot independently adopt or reject the same connector zone assignment');
  end if;
  select * into v_zone from public.network_zones
  where id = v_row.zone_id and organization_id = v_org;
  if p_decision = 'adopt' and (
    v_zone.id is null
    or v_zone.zone_status <> 'adopted'
    or v_zone.superseded_by_zone_id is not null
  ) then
    return jsonb_build_object('error', 'The assigned zone is no longer an adopted zone in this tenant');
  end if;
  if p_decision = 'adopt' then
    select * into v_current from public.connector_zone_assignments a
    where a.organization_id = v_org
      and a.connector_key = v_row.connector_key
      and a.assignment_status = 'adopted'
      and a.superseded_by_assignment_id is null
    for update;
    if found and v_row.supersedes_assignment_id is distinct from v_current.id then
      return jsonb_build_object('error', 'The proposal no longer supersedes the exact current assignment; submit a new revision');
    end if;
    if not found and v_row.supersedes_assignment_id is not null then
      return jsonb_build_object('error', 'The assignment selected for supersession is no longer current');
    end if;
  end if;

  v_status := case when p_decision = 'adopt' then 'adopted' else 'rejected' end;
  perform set_config('app.network_zone_writer', 'governed', true);
  if p_decision = 'adopt' and v_current.id is not null then
    update public.connector_zone_assignments
    set assignment_status = 'superseded', superseded_by_assignment_id = v_row.id
    where id = v_current.id and organization_id = v_org;
  end if;
  update public.connector_zone_assignments
  set assignment_status = v_status,
      decided_by = v_uid,
      decided_at = now(),
      decision_reason = btrim(p_reason)
  where id = v_row.id and organization_id = v_org;
  perform set_config('app.network_zone_writer', '', true);

  insert into public.audit_events(organization_id, entity_type, actor, event_data)
  values (
    v_org, 'connector_zone_assignment', v_role,
    jsonb_build_object(
      'event', 'connector_zone_assignment_' || v_status,
      'assignment_id', v_row.id,
      'version', v_row.version,
      'connector_key', v_row.connector_key,
      'zone_id', v_row.zone_id,
      'decision', p_decision,
      'proposed_by', v_row.proposed_by,
      'decided_by', v_uid,
      'segregation_of_duties', true,
      'aal', 'aal2',
      'verified_factor', true,
      'operational_authority', false
    )
  );
  insert into public.security_events(
    organization_id, actor_id, actor_label, event_type, severity, detail
  ) values (
    v_org, v_uid,
    (select coalesce(full_name, email) from public.user_profiles where id = v_uid),
    'admin_action', 'warning',
    'Connector ' || v_row.connector_key || ' zone assignment version ' || v_row.version || ' ' || v_status
  );

  return jsonb_build_object(
    'assignmentId', v_row.id,
    'version', v_row.version,
    'status', v_status,
    'segregationOfDuties', true,
    'operationalAuthority', false
  );
exception when others then
  perform set_config('app.network_zone_writer', '', true);
  raise;
end;
