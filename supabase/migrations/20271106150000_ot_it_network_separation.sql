create or replace function public.connector_zone_crossing(
  p_organization_id uuid,
  p_connector_key text,
  p_direction text
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $nz$
declare
  v_zone public.network_zones%rowtype;
  v_reason text;
begin
  if p_organization_id is null or btrim(coalesce(p_connector_key, '')) = '' then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'connector_and_tenant_required',
      'operational_authority', false
    );
  end if;
  if p_direction not in ('read', 'write') then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'unrecognized_direction',
      'operational_authority', false
    );
  end if;

  select z.* into v_zone
  from public.connector_zone_assignments a
  join public.network_zones z
    on z.id = a.zone_id
   and z.organization_id = a.organization_id
  where a.organization_id = p_organization_id
    and a.connector_key = btrim(p_connector_key)
    and a.assignment_status = 'adopted'
    and a.superseded_by_assignment_id is null
    and z.zone_status = 'adopted'
    and z.superseded_by_zone_id is null
  limit 1;

  if not found then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'no_adopted_zone_assignment',
      'operational_authority', false
    );
  end if;
  if v_zone.purdue_level is null then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'zone_level_not_declared',
      'zone_id', v_zone.id,
      'operational_authority', false
    );
  end if;
  -- Purdue 0–2 are the process, basic-control and supervisory levels already
  -- stored on the zone. This product does not write into that control zone
  -- (E5.16). The level is the customer's declaration, not a surveyed fact.
  if p_direction = 'write' and v_zone.purdue_level <= 2 then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'control_zone_write_refused',
      'zone_id', v_zone.id,
      'zone_key', v_zone.zone_key,
      'purdue_level', v_zone.purdue_level,
      'operational_authority', false
    );
  end if;
  if p_direction = 'write' and not v_zone.egress_permitted then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'egress_not_permitted',
      'zone_id', v_zone.id,
      'zone_key', v_zone.zone_key,
      'purdue_level', v_zone.purdue_level,
      'operational_authority', false
    );
  end if;
  if p_direction = 'write' and (v_zone.egress_route is null or btrim(v_zone.egress_route) = '') then
    return jsonb_build_object(
      'allowed', false,
      'reason', 'egress_route_required',
      'zone_id', v_zone.id,
      'operational_authority', false
    );
  end if;

  v_reason := case when p_direction = 'write' then 'adopted_egress' else 'adopted_zone_read' end;
  return jsonb_build_object(
    'allowed', true,
    'reason', v_reason,
    'zone_id', v_zone.id,
    'zone_key', v_zone.zone_key,
    'purdue_level', v_zone.purdue_level,
    'operational_authority', false
  );
end;
$nz$;

