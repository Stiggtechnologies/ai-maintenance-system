-- E5.03 — OT/IT network separation on the canonical zone tables.
--
-- Extends public.network_zones and public.connector_zone_assignments. It does
-- not create a second zone store, a second connector register, or a second
-- audit ledger. Customers declare the Purdue level already stored on the zone.
-- This migration does not survey a plant network, configure a firewall, or
-- write to a PLC, DCS, or safety system.
--
-- A named administrator or executive proposes. A different human, with a
-- verified factor and an AAL2 session, adopts or rejects. Direct DML is
-- refused. An assignment grants no operational authority.
--
-- Reads: once the tenant has any adopted zone, begin_connector_run refuses a
-- connector with no adopted assignment. A tenant with no adopted zone is
-- unzoned; the run still starts, and that is not separation.
--
-- Writes: SAP S/4HANA propose and execution-claim fail closed unless the
-- connector's adopted zone is outside Purdue 0–2, permits egress, and names a
-- route. Tests mock SAP. This migration does not call SAP.

